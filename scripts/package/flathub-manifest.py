#!/usr/bin/env python3
"""Writes the Flathub manifest for a release.

    scripts/package/flathub-manifest.py <tag> <commit> <output>

Flathub builds from its own repository (flathub/com.sanchezfauste.FaustePlayer),
which holds this manifest and cargo-sources.json. It is the in-tree
manifest (packaging/flatpak/com.sanchezfauste.FaustePlayer.yml) with the local
directory source replaced by the release's git tag and commit, so the two
never drift apart. Needs PyYAML.
"""

import pathlib
import sys

import yaml

REPO = "https://github.com/sanchezfauste/fauste-player.git"
HEADER = """\
# Generated by scripts/package/flathub-manifest.py in
# https://github.com/sanchezfauste/fauste-player from
# packaging/flatpak/com.sanchezfauste.FaustePlayer.yml. Do not edit here: change
# the source repository and release.
"""


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    tag, commit, output = sys.argv[1:]
    if len(commit) != 40:
        print(f"expected a full commit hash, got {commit!r}", file=sys.stderr)
        return 2
    root = pathlib.Path(__file__).resolve().parents[2]
    manifest = yaml.safe_load(
        (root / "packaging/flatpak/com.sanchezfauste.FaustePlayer.yml").read_text(encoding="utf-8")
    )
    modules = [m for m in manifest["modules"] if m.get("name") == "fauste-player"]
    if len(modules) != 1:
        print("the manifest has no fauste-player module", file=sys.stderr)
        return 1
    sources = modules[0]["sources"]
    replaced = [
        {"type": "git", "url": REPO, "tag": tag, "commit": commit}
        if isinstance(s, dict) and s.get("type") == "dir"
        else s
        for s in sources
    ]
    if replaced == sources:
        print("the manifest has no local directory source to replace", file=sys.stderr)
        return 1
    modules[0]["sources"] = replaced
    body = yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True, width=1000)
    pathlib.Path(output).write_text(HEADER + body, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
